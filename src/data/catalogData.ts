export function getLowestLabForTest(test: DiagnosticTest): {
  lab: LabPartner;
  price: number;
  savingsPercent: number;
  savingsAmount: number;
} {
  const entries = Object.entries(test.labPrices) as [
    LabPartner,
    { price: number; rating: number },
  ][];
  let bestLab: LabPartner = entries[0][0];
  let bestPrice = entries[0][1].price;
  for (const [lab, info] of entries) {
    if (info.price < bestPrice) {
      bestPrice = info.price;
      bestLab = lab;
    }
  }
  const savingsAmount = Math.max(0, test.mrp - bestPrice);
  const savingsPercent = Math.round((savingsAmount / test.mrp) * 100);
  return { lab: bestLab, price: bestPrice, savingsPercent, savingsAmount };
}
